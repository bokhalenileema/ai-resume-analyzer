def extract_skills(cleaned_text: str, skill_dict: dict) -> list:
    """
    Searches the cleaned resume text for controlled technical and job-related skills.
    """
    found_skills = set()
    for category, skills in skill_dict.items():
        for skill in skills:
            # Use word boundary regex matching to ensure precise skill detection
            pattern = r'\b' + re.escape(skill) + r'\b'
            if re.search(pattern, cleaned_text):
                found_skills.add(skill)

    return sorted(list(found_skills))

