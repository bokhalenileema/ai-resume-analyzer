def recommend_job_roles(resume_text: str, df_jobs: pd.DataFrame, top_n: int = 3) -> pd.DataFrame:
    """
    Converts resume and job descriptions into TF-IDF vectors, calculates cosine similarity,
    and ranks roles from highest to lowest score[cite: 4].
    """
    # Combine job role title and required skills for richer matching text
    job_texts = (df_jobs["Job Role"] + " " + df_jobs["Required Skills"]).tolist()

    # Include resume text as the first document in corpus
    corpus = [resume_text] + job_texts

    # Apply TF-IDF[cite: 2, 6]
    vectorizer = TfidfVectorizer(stop_words='english')
    tfidf_matrix = vectorizer.fit_transform(corpus)

    # Calculate cosine similarity between resume (index 0) and all job roles (indices 1 to end)
    resume_vector = tfidf_matrix[0:1]
    job_vectors = tfidf_matrix[1:]
    similarities = cosine_similarity(resume_vector, job_vectors).flatten()

    # Create results dataframe
    df_results = df_jobs.copy()
    df_results["Match Score (%)"] = (similarities * 100).round(2)

    # Sort by score descending and return top recommendations
    df_results = df_results.sort_values(by="Match Score (%)", ascending=False).reset_index(drop=True)
    return df_results.head(top_n)

