import re

def clean_resume_text(text: str) -> str:
    """
    Cleans raw resume text: converts to lowercase, removes unwanted symbols/extra spaces,
    while preserving important technical symbols like C++, C#, and .NET.
    """
    if not isinstance(text, str):
        return ""

    # Convert text to lowercase
    text = text.lower()

    # Replace special skill terms temporarily to protect special characters
    text = text.replace("c++", "CPLUSPLUS").replace("c#", "CSHARP").replace(".net", "DOTNET")

    # Remove unwanted punctuation and symbols
    text = re.sub(r'[^a-z0-9\s]', ' ', text)

    # Restore technical symbols
    text = text.replace("cplusplus", "c++").replace("csharp", "c#").replace("dotnet", ".net")

    # Remove extra spaces and newlines
    text = re.sub(r'\s+', ' ', text).strip()

    return text

