def analyze_skill_gaps_and_roadmap(resume_skills: list, target_role: str, df_jobs: pd.DataFrame) -> dict:
    """
    Compares extracted skills with target role requirements, identifies missing skills,
    and generates a rule-based learning roadmap.
    """
    row = df_jobs[df_jobs["Job Role"].str.lower() == target_role.lower()]
    if row.empty:
        return {"error": "Target role not found in dataset."}

    required_skills_str = row.iloc[0]["Required Skills"]
    required_skills = [s.strip() for s in required_skills_str.split(",")]

    # Find intersection and missing skills
    found_set = set(resume_skills)
    req_set = set(required_skills)

    matched_skills = sorted(list(found_set.intersection(req_set)))
    missing_skills = sorted(list(req_set - found_set))

    # Generate simple rule-based learning roadmap based on missing skills[cite: 6]
    roadmap = []
    for idx, skill in enumerate(missing_skills, start=1):
        roadmap.append(f"Week {idx}: Master fundamentals and practical implementation of {skill.upper()}")

    if not roadmap:
        roadmap.append("You possess all core required skills for this role! Focus on building advanced portfolio projects.")

    return {
        "Target Role": target_role,
        "Skills Found": matched_skills,
        "Missing Skills": missing_skills,
        "Learning Roadmap": roadmap
    }

